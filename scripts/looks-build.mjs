#!/usr/bin/env node
/**
 * Writes public/looks/<id>.cube for every look in config/looks/index.ts.
 *
 *   npm run looks:build            write every .cube
 *   npm run looks:build -- --check exit 1 if a .cube on disk differs from the numbers
 *
 * The look arithmetic is TypeScript shared with the app (lib/looks), so this bundles it with
 * esbuild into memory first; nothing else is needed and nothing is downloaded.
 */
import { build } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import os from "node:os";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "public", "looks");
const check = process.argv.includes("--check");

const entry = `
  export { LOOKS } from "@/config/looks";
  export { buildLut, serializeCube, LUT_SIZE } from "@/lib/looks/cube";
`;
const bundled = path.join(os.tmpdir(), `looks-build-${process.pid}.mjs`);
await build({
  stdin: { contents: entry, resolveDir: root, loader: "ts" },
  bundle: true,
  format: "esm",
  platform: "node",
  outfile: bundled,
  alias: { "@": root },
  logLevel: "silent",
});
const { LOOKS, buildLut, serializeCube, LUT_SIZE } = await import(pathToFileURL(bundled).href);

await mkdir(outDir, { recursive: true });
let stale = 0;
for (const look of LOOKS) {
  const lut = buildLut(look.grade, LUT_SIZE, `STUDIO SHALOM ${look.name}`);
  const text = serializeCube(lut, [
    `STUDIO SHALOM look "${look.id}" (${look.name} / ${look.nameKo})`,
    "Generated by scripts/looks-build.mjs from config/looks/index.ts. Do not edit by hand.",
    "Input and output: sRGB display levels 0-1.",
  ]);
  const file = path.join(outDir, `${look.id}.cube`);
  if (check) {
    const current = await readFile(file, "utf8").catch(() => null);
    if (current !== text) {
      stale++;
      console.error(`stale: ${path.relative(root, file)}`);
    }
  } else {
    await writeFile(file, text);
    console.log(
      `${path.relative(root, file)}  ${LUT_SIZE}³  ${(text.length / 1024).toFixed(0)} KB`,
    );
  }
}
if (check && stale) {
  console.error(`${stale} .cube file(s) do not match config/looks. Run: npm run looks:build`);
  process.exit(1);
}
if (check) console.log(`${LOOKS.length} .cube files match config/looks.`);
